#pragma once

#include <stdint.h>
#include <stdbool.h>
#include "esp_err.h"

// ============================================================================
//  电源键脉冲生成
//
//  设计要点（对应架构文档 5.7）：
//   - 脉冲在【独立任务】里生成，绝不在 MQTT 回调里直接拉 GPIO。
//     回调一旦被阻塞，脉冲宽度就失控 —— 超过 4 秒会触发主板强制断电。
//   - 本模块用队列接收请求，任务串行执行，天然限流。
// ============================================================================

// 初始化：配置 GPIO5 为输出并立即置低（上电默认安全态，越快越好）
void pulse_init(void);

// 投递一个"按一下电源键"请求。非阻塞，立即返回。
// 返回 ESP_OK 表示已入队；ESP_ERR_TIMEOUT 表示队列满（调用方应回复 busy）
esp_err_t pulse_request(uint16_t width_ms);

// 查询当前是否正在执行脉冲（用于状态上报/拒绝并发请求）
bool pulse_is_busy(void);